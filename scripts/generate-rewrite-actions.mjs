import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "grammar", "rewrite-front-actions.json");
const asmPath = path.join(root, "asm", "rewrite", "actions-generated.asmi");
const dispatchPath = path.join(
  root,
  "asm",
  "rewrite",
  "actions-escape-generated.asmi",
);
const typescriptPath = path.join(root, "src", "rewrite-actions-internal.ts");
const check = process.argv.includes("--check");
const source = JSON.parse(await readFile(sourcePath, "utf8"));

if (
  source.version !== 1 ||
  !Array.isArray(source.instructions) ||
  !Array.isArray(source.escapes) ||
  !Array.isArray(source.programs)
) {
  throw new Error("unsupported rewrite front-action source");
}

const names = new Set();
const instructions = source.instructions.map((instruction, id) => {
  if (
    !/^[A-Z][A-Za-z0-9]*$/.test(instruction.name) ||
    names.has(instruction.name) ||
    !Array.isArray(instruction.operands) ||
    instruction.operands.some(
      (operand) => !/^[a-z][A-Za-z0-9]*$/.test(operand),
    )
  ) {
    throw new Error(`invalid action instruction ${instruction.name}`);
  }
  names.add(instruction.name);
  return { ...instruction, id, width: 1 };
});
if (
  instructions.length === 0 ||
  instructions.length > 255 ||
  instructions[0]?.name !== "End" ||
  instructions[0]?.operands.length !== 0
) {
  throw new Error("action instruction zero must be operand-free End");
}

const escapeNames = new Set();
const escapes = source.escapes.map((escape, id) => {
  if (
    !/^[A-Z][A-Za-z0-9]*$/.test(escape.name) ||
    !/^[A-Z][A-Za-z0-9]*$/.test(escape.target) ||
    escapeNames.has(escape.name)
  ) {
    throw new Error(`invalid action escape ${escape.name}`);
  }
  escapeNames.add(escape.name);
  return { ...escape, id };
});
if (escapes.length === 0 || escapes.length > 255) {
  throw new Error("action escape count must be 1..255");
}

const instructionByName = new Map(
  instructions.map((instruction) => [instruction.name, instruction]),
);
const programNames = new Set();
const programs = source.programs.map((program) => {
  if (
    !/^[A-Z][A-Za-z0-9]*$/.test(program.name) ||
    programNames.has(program.name) ||
    !Array.isArray(program.steps) ||
    program.steps.length === 0
  ) {
    throw new Error(`invalid action program ${program.name}`);
  }
  programNames.add(program.name);
  const steps = program.steps.map((step) => {
    const instruction = instructionByName.get(step.instruction);
    if (
      instruction === undefined ||
      !Array.isArray(step.operands) ||
      step.operands.length !== instruction.operands.length ||
      step.operands.some(
        (operand) =>
          !Number.isInteger(operand) &&
          (typeof operand !== "string" || !/^[A-Z][A-Za-z0-9]*$/.test(operand)),
      )
    ) {
      throw new Error(`invalid ${program.name} action step ${step.instruction}`);
    }
    return { ...step, id: instruction.id, width: instruction.width };
  });
  if (steps.at(-1)?.instruction !== "End") {
    throw new Error(`action program ${program.name} must end with End`);
  }
  return {
    ...program,
    steps,
    width: steps.length,
  };
});

const expectationKeys = new Map();
const expectations = [];
for (const program of programs) {
  for (const step of program.steps) {
    if (step.instruction !== "Expect") continue;
    const [token, diagnostic] = step.operands;
    const key = `${token}\0${diagnostic}`;
    if (expectationKeys.has(key)) continue;
    const id = expectations.length;
    expectationKeys.set(key, id);
    expectations.push({ id, token, diagnostic, code: id + 1 });
  }
}
if (expectations.length === 0 || expectations.length > 127) {
  throw new Error("action expectation count must be 1..127");
}
if (escapes.length > 128) {
  throw new Error("dense action escape count must be at most 128");
}

const expectationName = ({ token, diagnostic }) =>
  `RewriteActionExpect${token}${diagnostic}`;
const encodedStep = (step) => {
  if (step.instruction === "End") return "RewriteActionEnd";
  if (step.instruction === "Expect") {
    const [token, diagnostic] = step.operands;
    const expectation = expectations[expectationKeys.get(`${token}\0${diagnostic}`)];
    if (expectation === undefined) throw new Error("missing action expectation");
    return expectationName(expectation);
  }
  if (step.instruction === "Escape") return String(step.operands[0]);
  throw new Error(`unsupported dense action instruction ${step.instruction}`);
};

const asm = [
  "; Generated by scripts/generate-rewrite-actions.mjs. Do not edit.",
  "; Every instruction occupies one byte. Expectation codes are 1..127 and",
  "; escape codes have bit 7 set. Escape addresses remain complete words in",
  "; the generated dispatcher; the bytecode therefore imposes no origin policy.",
  "",
  "RewriteActionEnd .equ 0",
  `RewriteActionInstructionCount .equ ${instructions.length}`,
  "RewriteActionMaximumWidth .equ 1",
  `RewriteActionExpectCount .equ ${expectations.length}`,
  ...expectations.map(
    (expectation) => `${expectationName(expectation)} .equ ${expectation.code}`,
  ),
  "RewriteActionEscapeMask .equ $80",
  "",
  ...escapes.map(
    ({ name, id }) => `RewriteActionEscape${name} .equ RewriteActionEscapeMask+${id}`,
  ),
  `RewriteActionEscapeCount .equ ${escapes.length}`,
  "",
  ...programs.flatMap(({ name, steps, width }) => [
    `RewriteActionProgram${name}:`,
    ...steps.map((step) => `            .db ${encodedStep(step)}`),
    `RewriteActionProgram${name}End:`,
    `RewriteActionProgram${name}Width .equ ${width}`,
    "",
  ]),
  "RewriteActionExpectationTable:",
  ...expectations.map(
    ({ token, diagnostic }) => `            .db ${token},${diagnostic}`,
  ),
  "",
].join("\n");

const dispatch = [
  "; Generated by scripts/generate-rewrite-actions.mjs. Do not edit.",
  "; The caller validates A before entering this full-address dispatcher.",
  "; The directory contains relocatable 16-bit addresses. Selectors never",
  "; borrow or discard address bits and therefore impose no origin policy.",
  "",
  ".routine in A out A,carry,zero clobbers sign,parity,halfCarry,B,C,D,DE,HL,IX,IY",
  "RewriteActionEscapeDispatch:",
  "            LD   L,A",
  "            LD   H,0",
  "            ADD  HL,HL",
  "            LD   DE,RewriteActionEscapeDirectory",
  "            ADD  HL,DE",
  "            LD   E,(HL)",
  "            INC  HL",
  "            LD   D,(HL)",
  "            EX   DE,HL",
  "            JP   (HL)",
  "RewriteActionEscapeDirectory:",
  ...escapes.map(({ name, target }) =>
    `            .dw ${target} ; ${name}`,
  ),
  "",
].join("\n");

const typescript = [
  "// Generated by scripts/generate-rewrite-actions.mjs. Do not edit.",
  "",
  "export interface RewriteActionInstruction {",
  "  readonly id: number;",
  "  readonly name: string;",
  "  readonly operands: readonly string[];",
  "  readonly width: number;",
  "}",
  "",
  `export const rewriteActionInstructions: readonly RewriteActionInstruction[] = ${JSON.stringify(instructions, null, 2)};`,
  `export const rewriteActionExpectations = ${JSON.stringify(expectations, null, 2)} as const;`,
  `export const rewriteActionEscapes = ${JSON.stringify(escapes, null, 2)} as const;`,
  `export const rewriteActionPrograms = ${JSON.stringify(programs, null, 2)} as const;`,
  "",
  "export const decodeRewriteActionProgram = (bytes: Uint8Array): readonly number[] => {",
  "  const starts: number[] = [];",
  "  let cursor = 0;",
  "  while (cursor < bytes.length) {",
  "    const start = cursor;",
  "    const code = bytes[cursor] ?? -1;",
  "    if (code !== 0 && (code & 0x80) === 0 && rewriteActionExpectations[code - 1] === undefined) {",
  "      throw new Error(`invalid rewrite action expectation at byte ${cursor}`);",
  "    }",
  "    if ((code & 0x80) !== 0 && rewriteActionEscapes[code & 0x7f] === undefined) {",
  "      throw new Error(`invalid rewrite action escape at byte ${cursor}`);",
  "    }",
  "    starts.push(start);",
  "    cursor += 1;",
  "    if (code === 0) {",
  "      if (cursor !== bytes.length) throw new Error(`trailing rewrite action bytes at ${cursor}`);",
  "      return starts;",
  "    }",
  "  }",
  "  throw new Error(\"rewrite action program has no End\");",
  "};",
  "",
].join("\n");

const writeOrCheck = async (target, value) => {
  if (check) {
    const current = await readFile(target, "utf8");
    if (current !== value) throw new Error(`${path.relative(root, target)} is stale`);
    return;
  }
  await writeFile(target, value, "utf8");
};

await writeOrCheck(asmPath, asm);
await writeOrCheck(dispatchPath, dispatch);
await writeOrCheck(typescriptPath, typescript);
