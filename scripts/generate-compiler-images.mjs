import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "@jhlagado/azm/compile";

await import("./check-azm-toolchain.mjs");
await import("./generate-rewrite-operations.mjs");

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = path.join(root, "asm", "vertical-slice");
const outputPath = path.join(root, "src", "generated-compiler-images.ts");

const assemble = async (debug) => {
  const source = path.join(
    sourceDirectory,
    debug ? "flat-target-debug-z80-slice-proof.asm" : "flat-target-z80-slice-proof.asm",
  );
  const result = await compile(source, {
    emitBin: false,
    emitHex: true,
    emitD8m: true,
    registerContracts: "strict",
    registerContractsInterfaces: [
      path.join(sourceDirectory, "expression-generated-z80.asmi"),
    ],
  });
  const errors = result.diagnostics.filter(({ severity }) => severity === "error");
  if (errors.length > 0) {
    throw new Error(
      errors
        .map(
          ({ sourceName, line, column, message }) =>
            `${sourceName ?? source}:${line ?? "?"}:${column ?? "?"} ${message}`,
        )
        .join("\n"),
    );
  }
  const hex = result.artifacts.find((artifact) => artifact.kind === "hex");
  const d8m = result.artifacts.find((artifact) => artifact.kind === "d8m");
  if (hex?.kind !== "hex" || d8m?.kind !== "d8m") {
    throw new Error(`AZM omitted generated compiler artifacts for ${source}`);
  }
  const symbols = Object.fromEntries(
    d8m.json.symbols.flatMap((entry) => {
      const value = entry.address ?? entry.value;
      return value === undefined ? [] : [[entry.name, value]];
    }),
  );
  return { hex: hex.text, symbols };
};

const [normal, debug] = await Promise.all([assemble(false), assemble(true)]);
const generated = `// Generated by scripts/generate-compiler-images.mjs. Do not edit.\n\nexport const normalCompilerHex = ${JSON.stringify(normal.hex)};\nexport const normalCompilerSymbols: Readonly<Record<string, number>> = ${JSON.stringify(normal.symbols, null, 2)};\n\nexport const debugCompilerHex = ${JSON.stringify(debug.hex)};\nexport const debugCompilerSymbols: Readonly<Record<string, number>> = ${JSON.stringify(debug.symbols, null, 2)};\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    // The mismatch below reports a missing generated file.
  }
  if (current !== generated) {
    throw new Error("generated Nucleus compiler images are stale; run npm run generate:compiler-images");
  }
} else {
  await writeFile(outputPath, generated, "utf8");
}
