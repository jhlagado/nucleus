import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { assembleImageInWorker } from "./assemble-image-worker.mjs";

for (const argument of process.argv.slice(2)) {
  if (argument !== "--check") {
    throw new Error(`Unknown argument: ${argument}; generation uses ATOM only`);
  }
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = path.join(root, "asm", "vertical-slice");
const outputPath = path.join(root, "src", "generated-compiler-images.ts");

const assemble = (debug) => assembleImageInWorker(path.join(
    sourceDirectory,
    debug ? "flat-target-debug-z80-slice-proof.asm" : "flat-target-z80-slice-proof.asm",
  ));

const [normal, debug] = await Promise.all([assemble(false), assemble(true)]);
const generated = `// Generated by scripts/generate-compiler-images.mjs using ATOM. Do not edit.\n\nexport const normalCompilerHex = ${JSON.stringify(normal.hex)};\nexport const normalCompilerSymbols: Readonly<Record<string, number>> = ${JSON.stringify(normal.symbols, null, 2)};\n\nexport const debugCompilerHex = ${JSON.stringify(debug.hex)};\nexport const debugCompilerSymbols: Readonly<Record<string, number>> = ${JSON.stringify(debug.symbols, null, 2)};\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    // The mismatch below reports a missing generated file.
  }
  if (current !== generated) {
    throw new Error("generated Nucleus compiler images are stale; run npm run generate:compiler-images");
  }
} else {
  await writeFile(outputPath, generated, "utf8");
}
